"""vbidata.inc for vbiplay.s: the engine RAM image, the band-limit table, the songs."""
import sys, os
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'test', 'engine')
sys.path.insert(0, P)
import engmodel, mkinst, mksongs

SONGS = ['CANTINA', 'ENTERTA', 'MINWALTZ', 'BENIHILL', 'BACHCOR', 'TULL']
def freq0(clk, ntsc):         # frequency word of note code 0
    return (engmodel.A440 + engmodel.fcorr(clk, ntsc) - 73 * 64) & 0x1FFF

def runs(ram):
    """contiguous runs of words 41..255 (word 40, the pitch, is set at run time)"""
    ws = sorted(w for w in ram if w > 40)
    out = []
    for w in ws:
        if out and out[-1][0] + len(out[-1][1]) == w and len(out[-1][1]) < 63:
            out[-1][1].append(ram[w])
        else:
            out.append((w, [ram[w]]))
    return out

def main(out, clk4='2x'):
    ram = engmodel.ram_image(clk4)
    ram = {w: v for w, v in ram.items() if w >= 40}          # voice states: set by instrument events
    names = [i['name'] for i in engmodel.instruments(clk4)]
    hm = engmodel.hmax(clk4)
    L = ['; generated by mkvbi.py: do not edit (AMY clock %s: engine UNIT_LOG2 = %d)' % (engmodel.clock(clk4), engmodel.UNIT_LOG2[clk4]), '']
    L.append('freq0_pal:  .word $%04X' % freq0(clk4, False))
    L.append('freq0_ntsc: .word $%04X' % freq0(clk4, True))
    L.append('; engine RAM: runs of (first word, count, count x 4 bytes), 0 ends')
    L.append('engram:')
    for w, vals in runs(ram):
        L.append('        .byte %d, %d' % (w, len(vals)))
        for i in range(0, len(vals), 4):
            L.append('        .byte ' + ', '.join('$%02X,$%02X,$%02X,$%02X' % (v & 255, (v >> 8) & 255, (v >> 16) & 255, (v >> 24) & 255) for v in vals[i:i + 4]))
    L.append('        .byte 0')
    L.append('; harmonics below the band limit, by note code (64 = C4)')
    t = [hm[min(c - 64 - engmodel.HMAX_LO, len(hm) - 1)] for c in range(128)]
    L.append('hmtab:')
    for i in range(0, 128, 16):
        L.append('        .byte ' + ','.join(str(x) for x in t[i:i + 16]))
    L.append('NSONGS = %d' % len(SONGS))
    L.append('song_lo: .byte ' + ','.join('<song_%d' % i for i in range(len(SONGS))))
    L.append('song_hi: .byte ' + ','.join('>song_%d' % i for i in range(len(SONGS))))
    L.append('; instrument of each voice, per song (ensemble = song number)')
    L.append('song_inst:')
    for i in range(len(SONGS)):
        ens = mkinst.ENSEMBLES[i % len(mkinst.ENSEMBLES)]
        L.append('        .byte ' + ','.join(str(names.index(x)) for x in ens[1]) + '   ; ' + ens[0])
    L.append('song_name:')
    for i, s in enumerate(SONGS):
        ens = mkinst.ENSEMBLES[i % len(mkinst.ENSEMBLES)][0]
        txt = ('%-9s %-9s' % (s, ens))[:20]
        L.append('        .byte "%s"' % txt)
    for i, s in enumerate(SONGS):
        b = mksongs.encode(os.path.join(P, 'songs', s + '.MUS'))
        L.append('song_%d:   ; %s, %d bytes' % (i, s, len(b)))
        for j in range(0, len(b), 16):
            L.append('        .byte ' + ','.join('$%02X' % x for x in b[j:j + 16]))
    open(out, 'w').write('\n'.join(L) + '\n')

if __name__ == '__main__':
    # usage: mkvbi.py [out.inc] [2x | 4x | clk8]   (the AMY clock, mkinst.CLOCKS)
    main(sys.argv[1] if len(sys.argv) > 1 else 'vbidata.inc', sys.argv[2] if len(sys.argv) > 2 else '2x')
