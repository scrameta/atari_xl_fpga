#!/usr/bin/env python3
"""AMY1 host-command stimulus builder (port of the 1985 GENERATOR.PAS API).

Writes a Verilog include with timed 6502-style bus writes that tb_cmd.v replays.
Times are in SILOS cycles (5 ns). Bus timing follows GENERATOR.PAS: phi2 = 1.7 MHz,
address/data set up for phi2-low (59 units), WR low for phi2-high (59 units), 2 units hold.
"""
import sys

CMD, AREG, BREG, CREG = 0, 1, 2, 3
WRFFBP, WRHABP, WRSOR, WRSCR, WRVTYP, CLRLHPF, SETLHPF = 0x08, 0x40, 0x20, 0x30, 0x10, 0x80, 0x81
SIXTY_FOUR, FORTY = 0x0, 0x8
SUM_MODE, INDIVIDUAL = 0x0, 0x4
SEQ_RUN, SEQ_HALT, NOISE_INIT, NOISE_RUN = 0x1, 0x0, 0x2, 0x0

PHI2 = 59                # 294 ns in 5 ns units
CPU = 2 * PHI2


class Stim:
    def __init__(self):
        self.t = 2 * CPU          # after reset (reset held for one cpu cycle by tb)
        self.ev = []
        self.regs = {}

    def advance(self, units):
        self.t += int(round(units))

    def write(self, addr, data, skip_same=True):
        if skip_same and addr != CMD and self.regs.get(addr) == data:
            return
        self.regs[addr] = data
        self.ev.append((self.t, addr, data & 0xFF))
        self.t += 2 * CPU         # one bus cycle + idle cycle, as sendit()

    # --- the GENERATOR.PAS procedures
    def system_options(self, harmonics=SIXTY_FOUR, mode=SUM_MODE):
        self.write(CMD, WRSOR | harmonics | mode); self.advance(2 * CPU)

    def system_control(self, seq=SEQ_RUN, noise=NOISE_RUN):
        self.write(CMD, WRSCR | seq | noise); self.advance(2 * CPU)

    def voice_type(self, vtype, voice):
        self.write(AREG, vtype); self.advance(CPU)
        self.write(CMD, WRVTYP + voice); self.advance(2 * CPU)

    def lhp(self, flag, on=True):
        self.write(CMD, (SETLHPF if on else CLRLHPF) + 2 * flag); self.advance(2 * CPU)

    def frequency(self, freq, slope, voice):
        self.write(AREG, slope); self.advance(CPU)
        self.write(BREG, freq >> 8); self.advance(CPU)
        self.write(CREG, freq & 0xFF); self.advance(CPU)
        self.write(CMD, WRFFBP + voice); self.advance(2 * CPU)

    def amplitude(self, amp, slope, harmonic):
        self.write(AREG, slope); self.advance(CPU)
        self.write(CREG, amp); self.advance(CPU)
        self.write(CMD, WRHABP + harmonic); self.advance(2 * CPU)

    def wait_samples(self, n):
        self.advance(n * 6144)

    def emit(self, path):
        with open(path, 'w') as f:
            f.write('// generated by mkcmd.py: bus_write(time, addr, data)\n')
            for t, a, d in self.ev:
                f.write(f'    bus_write({t}, {a}, 8\'h{d:02x});\n')
            f.write(f'    // end of command stream at {self.t}\n')
        return self.t


def quickclr():
    """The deck's QUICKCLR test: voice 0 at note C with harmonics 0 and 1."""
    s = Stim()
    s.system_options()
    s.lhp(0)
    s.amplitude(0xF0, 0, 0)
    s.amplitude(0xF0, 0, 1)
    s.frequency(0x174C, 0, 0)
    s.frequency(0x1A4C, 0, 1)
    s.advance(10 * CPU)
    s.system_control()
    return s


def quickclr_ni():
    """QUICKCLR preceded by a noise-initialise phase (sequencer halted, noise init mode)."""
    s = Stim()
    s.system_control(seq=SEQ_RUN, noise=NOISE_INIT)
    s.wait_samples(4)
    s.system_options()
    s.lhp(0)
    s.amplitude(0xF0, 0, 0)
    s.amplitude(0xF0, 0, 1)
    s.frequency(0x174C, 0, 0)
    s.frequency(0x1A4C, 0, 1)
    s.advance(10 * CPU)
    s.system_control()
    return s


def spec_init(s, lhp_set=(0,)):
    """Initialisation per the AMY 1 spec, section 8 (no noise generators used)."""
    s.system_options()
    for v in range(8):
        s.voice_type(0, v)              # harmonic voice -> noise disabled for that voice
    for h in range(64):
        s.amplitude(0, 0, h)            # immediate to zero
    for f in range(32):
        s.lhp(f, f in lhp_set)


def quickclr_spec():
    """QUICKCLR musical content, but with the spec's initialisation sequence first."""
    s = Stim()
    spec_init(s, lhp_set=(0,))
    s.amplitude(0xF0, 0, 0)
    s.amplitude(0xF0, 0, 1)
    s.frequency(0x174C, 0, 0)
    s.frequency(0x1A4C, 0, 1)
    s.advance(10 * CPU)
    s.system_control()
    return s


def rich():
    """Two voices, several harmonics with different levels, envelopes and a glide."""
    s = Stim()
    s.system_options()
    s.lhp(3)                          # voice 0 = harmonics 0..7, voice 1 = 8..63
    s.frequency(0x174C, 0, 0)         # voice 0: C
    s.frequency(0x174C + 0x1C0, 0, 1) # voice 1: G above
    s.amplitude(0xF0, 0, 0)
    s.amplitude(0xC8, 0, 1)
    s.amplitude(0xB0, 0, 2)
    s.amplitude(0xE0, 0x20, 8)        # voice 1 fundamental, with a slope
    s.system_control()
    s.wait_samples(60)
    s.frequency(0x174C + 0x100, 0x22, 0)   # glide voice 0 up, slope 0x22
    s.amplitude(0x60, 0x23, 0)              # fade harmonic 0 down
    s.amplitude(0xF0, 0x21, 3)              # bring in harmonic 3
    return s


def rich_spec():
    """Spec initialisation, then two voices with envelopes, a glide and a harmonic swap."""
    s = Stim()
    spec_init(s, lhp_set=(3,))       # voice 0 = harmonics 0..7, voice 1 = 8..63
    s.frequency(0x174C, 0, 0)
    s.frequency(0x174C + 0x1C0, 0, 1)
    s.system_control()
    s.amplitude(0xF0, 0, 0)
    s.amplitude(0xC8, 0, 1)
    s.amplitude(0xB0, 0, 2)
    s.amplitude(0xE0, 0x20, 8)
    s.wait_samples(40)
    s.frequency(0x174C + 0x100, 0x22, 0)
    s.amplitude(0x60, 0x23, 0)
    s.amplitude(0xF0, 0x21, 3)
    s.wait_samples(40)
    s.amplitude(0x00, 0x24, 8)
    s.frequency(0x174C - 0x300, 0x41, 1)
    return s


if __name__ == '__main__':
    which, out = sys.argv[1], sys.argv[2]
    end = {'quickclr': quickclr, 'quickclr_ni': quickclr_ni, 'quickclr_spec': quickclr_spec, 'rich': rich, 'rich_spec': rich_spec}[which]().emit(out)
    print(f'{which}: commands end at t={end}')
