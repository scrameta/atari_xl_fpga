"""Convert Atari Music Composer files (via mus.py, a port of PARSE.C from the 1983
AMY Music Box) into songs.h for amybox.c.

Song blob:  tempo, ndur, ndur x (on, gap), then 4 x 16-bit LE offsets (from blob start)
of the voice streams.  Voice stream bytes:
   0x00          end of voice
   0x01 v        base velocity v (the first note of each measure gets +16)
   0x02 d        rest for duration pair d
   n    d        note: n & 0x7F = semitones from C4 + 64, n & 0x80 = accent
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mus

def encode(path):
    tempo, voices, _ = mus.parse(open(path, 'rb').read())
    durs = []
    def di(on, gap):
        assert 1 <= on <= 255 and 1 <= gap <= 255, (on, gap)
        if (on, gap) not in durs: durs.append((on, gap))
        return durs.index((on, gap))
    streams = []
    for v in voices:
        out = []; base = None
        for n, vel, on, gap in v:
            d = di(on, gap)
            if n is None:
                out += [2, d]; continue
            b = vel & ~16
            if b != base: out += [1, b]; base = b
            code = n + 64; assert 3 <= code <= 127
            out += [code | (0x80 if vel & 16 else 0), d]
        out.append(0)
        streams.append(out)
    assert len(durs) < 256
    hdr = [tempo, len(durs)] + [x for p in durs for x in p]
    off = len(hdr) + 8; blob = hdr[:]
    offs = []
    for s in streams:
        offs.append(off); off += len(s)
    for o in offs: blob += [o & 255, o >> 8]
    for s in streams: blob += s
    return blob

def main(out, files):
    lines = ['/* generated by mksongs.py from the 1983 AMY demo disks: do not edit */']
    names = []
    total = 0
    for f in files:
        name = os.path.splitext(os.path.basename(f))[0].upper()
        blob = encode(f); total += len(blob)
        cname = 's_' + name.lower()
        lines.append('static const unsigned char %s[%d] = {' % (cname, len(blob)))
        for i in range(0, len(blob), 20):
            lines.append('  ' + ','.join(str(x) for x in blob[i:i + 20]) + ',')
        lines.append('};')
        names.append((name, cname))
    lines.append('#define NSONGS %d' % len(names))
    lines.append('static const char * const song_name[NSONGS] = {' + ','.join('"%s"' % n for n, _ in names) + '};')
    lines.append('static const unsigned char * const song_data[NSONGS] = {' + ','.join(c for _, c in names) + '};')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('songs', len(names), 'bytes', total)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2:])
