"""convdata.inc for amyconv.s: engine RAM image, tables, the tunes' streams."""
import sys, os
H = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, H)
import arrange, encode, instruments as I, build
import static_tables
SAP = os.path.join(H, '..', 'asma', 'asma', 'Composers')
# Tune sets, one XEX each (a set's streams must fit in the 6502's memory: about 31 KB)
SETS = {
    1: [('DRACONUS', 'ADAM GILMORE 1988', 'Gilmore_Adam/Draconus.sap', 0, 8985),
        ('ZYBEX', 'ADAM GILMORE 1988', 'Gilmore_Adam/Zybex.sap', 4, 6545),
        ('WARHAWK', 'ROB HUBBARD 1986', 'Hubbard_Rob/Warhawk.sap', 0, 10870)],
    2: [('HAPPY TRAIN', 'ADAM BIENIAS 1994', 'Bienias_Adam/Happy_Train_to_Kingdom_of.sap', 0, 10967),
        ('AXEL F', 'TORSTEN KARWOTH 1990', 'Karwoth_Torsten/Axel_F.sap', 0, 5678),
        ('BITTER REALITY', 'ADAM BIENIAS', 'Bienias_Adam/Bitter_Reality.sap', 0, 4429)],
    3: [('INTERNATIONAL KARATE', 'ROB HUBBARD', 'Hubbard_Rob/International_Karate.sap', 0, 9000),
        ('JET SET WILLY', 'ROB HUBBARD', 'Hubbard_Rob/Jet_Set_Willy.sap', 0, 9000)],
    # a ProTracker module (mod2amy.py, mod/): DJ Metune's 2015 Amiga cover, the whole song
    4: [('AXEL F', 'DJ METUNE 2015 (AMIGA MOD)', 'axelf.mod', 0, 9208)],
}
TUNES = SETS[int(os.environ.get('AMYCONV_SET', '1'))]
BASE = 0x5000                       # where the first stream is assembled (checked by the .org)

def tables():
    return static_tables.tables()

def main(out):
    L = ['; generated by mkconv.py: do not edit', ''] + tables()
    L.append('NTUNES = %d' % len(TUNES))
    L.append('tune_lo: .byte ' + ','.join('<tune_%d' % i for i in range(len(TUNES))))
    L.append('tune_hi: .byte ' + ','.join('>tune_%d' % i for i in range(len(TUNES))))
    L.append('tname_lo: .byte ' + ','.join('<tname_%d' % i for i in range(len(TUNES))))
    L.append('tname_hi: .byte ' + ','.join('>tname_%d' % i for i in range(len(TUNES))))
    for i, (name, who, *_) in enumerate(TUNES):
        L.append('tname_%d: .byte "%-36s"' % (i, ('%s  %s' % (name, who))[:36]))
    stats = []
    for i, (name, who, sap, song, fr) in enumerate(TUNES):
        hdr, ev, vi, st = arrange.arrange(os.path.join(SAP, sap), song, fr)
        tok = encode.tokens(ev, fr)
        data, nref = encode.compress(tok, BASE)
        refs = list(encode.compress.refs)
        assert encode.decode(data, BASE) == tok
        L.append('tune_%d:   ; %s, %d frames, %d bytes (%d raw)' % (i, name, fr, len(data), sum(map(len, tok))))
        L += encode.asm(data, BASE, 'tune_%d' % i, refs)
        stats.append((name, len(data)))
    open(out, 'w').write('\n'.join(L) + '\n')
    return stats

if __name__ == '__main__':
    print(main(sys.argv[1] if len(sys.argv) > 1 else 'convdata.inc'))
