"""Basic standalone sanity check. No py65 or assembler required."""
import hashlib
import math
import re
from pathlib import Path
import instruments as I
import engmodel
import mkinst
import static_tables


def main():
    assert I.CLK == 'clk8192'
    assert mkinst.CLOCKS[I.CLK] == (8192000.0, -26, -26)
    assert mkinst.clock_fs(I.CLK) == 32000.0
    assert abs(I.UNIT_S - 0.008) < 1e-12
    assert engmodel.A440 + engmodel.fcorr(I.CLK) == 0x1372
    assert I.FREQ0 == 0x0132
    assert abs(768 * math.log2(7168000 / 8192000) + 147.95141985976) < 1e-7

    data = Path(__file__).with_name('convdata.inc').read_text()
    prefix = '; generated by mkconv.py: do not edit\n\n' + '\n'.join(static_tables.tables()) + '\n'
    assert data.startswith(prefix), 'convdata.inc static tables do not match selected clock'
    e = data.index('engram:')
    a = data.index('ftab_lo:')
    assert '$32,$01,$00,$00' in data[e:a], 'engine note-0 pitch wrong'
    assert '$C6,$01,$00,$00' not in data[e:a], 'old engine note-0 pitch remains'
    freq = [(I.FREQ0 + n * 64) & 0x1FFF for n in range(128)]
    assert freq[73] == 0x1372
    def parse_label(label):
        part = data.split(label + ':\n', 1)[1].split('\n', 8)[0:8]
        vals = []
        for line in part:
            vals += [int(n, 16) for n in re.findall(r'\$([0-9A-F]{2})', line)]
        return vals
    lo, hi = parse_label('ftab_lo'), parse_label('ftab_hi')
    assert len(lo) == len(hi) == 128
    assert [(h << 8) | l for h, l in zip(hi, lo)] == freq
    print('PASS clock, A440, engine reference, 128 pitch entries, static tables, engine timebase')
    print('A440=$%04X, note0=$%04X, audio sample rate %d Hz, engine quantum %.3f ms' %
          (freq[73], I.FREQ0, mkinst.clock_fs(I.CLK), I.UNIT_S * 1000))

if __name__ == '__main__':
    main()
