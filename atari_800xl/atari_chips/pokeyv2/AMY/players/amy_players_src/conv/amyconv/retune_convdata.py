"""Retune existing convdata.inc for the chosen AMY clock without SAP sources.

Rebuilds engine instrument RAM, frequency and harmonic tables from current
instrument definitions, leaving all encoded song streams byte-for-byte intact.
Re-run ca65/ld65 to generate a new .xex: the checked-in binary is not patched.
"""
import argparse
from pathlib import Path
import static_tables


def retune(path):
    old = path.read_text()
    marker = 'NTUNES = '
    assert old.count(marker) == 1, 'expected a unique beginning of tune streams'
    tail = old[old.index(marker):]
    prefix = '; generated by mkconv.py: do not edit\n\n' + '\n'.join(static_tables.tables()) + '\n'
    # The tune table and all compressed song data are intentionally unchanged.
    path.write_text(prefix + tail)
    print('Retuned static AMY tables in %s (%d song-data bytes preserved)' % (path, len(tail)))


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('file', nargs='?', type=Path, default=Path(__file__).with_name('convdata.inc'))
    ns = ap.parse_args()
    retune(ns.file)
