#!/usr/bin/env python3
"""copgen.py WORDS.json OUT - a player's copper note engine, from its engine RAM image.

WORDS.json: {"hpv": 8 or 16, "ninst": n, "ram": {addr: word}, "xram": {addr: word}} (the words
the player used to upload to the note engine: base page and extension page).

Writes:
  OUT.bin   the image for sample RAM at $E000 (stubs, tables, code)
  OUT.xex   an Atari load segment that uploads the image to the PokeyMAX sample RAM when it
            is loaded (INITAD), if the core has the copper (it checks for a PokeyMAX, then
            RESTRICT bit 7 = 0 before it reads CAPABILITY2, so it writes nothing on an older
            core), then is overwritten by the player: prepend it to the player's
            XEX (cat OUT.xex player.xex > final.xex), so the image costs the player no memory
  OUT.h     C:    COP_PAGE_X, COP_PAGE_L (the page of the single entries; the combined ones are
                  on the next page), COP_VINIT, COP_CUT, COP_VIB, COP_SEL(i), COP_ON(i),
                  COP_OFF(i), COP_SELON(i), COP_ONOFF(i), COP_ON2(i), COP_OFFON(i)
  OUT.inc   ca65: the same as constants (COP_SEL0 ... COP_OFFON0 and COP_STRIDE)"""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from amycop import CopperAmy, STUBS, OPS, COMBOS

LOADER = 0x4000


def loader_xex(img, base):
    """$FFFF, the uploader and the image at LOADER, then INITAD -> the uploader"""
    pages = (len(img) + 255) // 256
    img = img + bytes(pages * 256 - len(img))
    code_len = 0x4E
    src = LOADER + 0x60                                    # the image
    c = bytearray([
        0xA9, 0x3F, 0x8D, 0x0C, 0xD2,                       # LDA #$3F : STA $D20C   map the config in
        0xA2, 0x00,                                         # LDX #0                 no copper yet
        0xAD, 0x1C, 0xD2, 0xC9, 0x01, 0xD0, 0x0F,           # LDA $D21C : CMP #1 : BNE nope   a PokeyMAX?
        0xAD, 0x17, 0xD2, 0x30, 0x0A,                       # LDA $D217 : BMI nope   RESTRICT bit 7 = 1: an older core
        0xAD, 0x20, 0xD2, 0x29, 0x06, 0xC9, 0x06, 0xD0, 0x01,   # CAPABILITY2: copper and 64 KiB?
        0xE8,                                               # INX
        0xA9, 0x00, 0x8D, 0x0C, 0xD2,                       # nope: LDA #0 : STA $D20C   map it out
        0x8A, 0xF0, 0x28,                                   # TXA : BEQ done
        0xA9, 0x03, 0x8D, 0x95, 0xD2,                       # LDA #3 : STA CCTRL     copper: stop all threads
        0xA9, base & 255, 0x8D, 0x84, 0xD2,                 # RAMADDR = base
        0xA9, base >> 8, 0x8D, 0x85, 0xD2,
        0xA9, src & 255, 0x85, 0xCB,                        # ($CB) = the image
        0xA9, src >> 8, 0x85, 0xCC,
        0xA2, pages, 0xA0, 0x00,                            # LDX #pages : LDY #0
        0xB1, 0xCB, 0x8D, 0x87, 0xD2,                       # loop: LDA ($CB),Y : STA RAMDATAINC
        0xC8, 0xD0, 0xF8,                                   # INY : BNE loop
        0xE6, 0xCC, 0xCA, 0xD0, 0xF3,                       # INC $CC : DEX : BNE loop
        0x60])                                              # done: RTS
    assert len(c) == code_len, len(c)
    body = bytes(c) + bytes(0x60 - len(c)) + img
    end = LOADER + len(body) - 1
    x = bytearray([0xFF, 0xFF, LOADER & 255, LOADER >> 8, end & 255, end >> 8]) + body
    x += bytes([0xE2, 0x02, 0xE3, 0x02, LOADER & 255, LOADER >> 8])
    return bytes(x)


def main():
    src, out = sys.argv[1], sys.argv[2]
    d = json.load(open(src))
    ram = {int(k): v for k, v in d['ram'].items()}
    xram = {int(k): v for k, v in d['xram'].items()}
    c = CopperAmy(ram, xram, d['hpv'], d['ninst'])
    base, img = c.image()
    open(out + '.bin', 'wb').write(img)
    open(out + '.xex', 'wb').write(loader_xex(img, base))
    e = c.entry
    stride = (e[('sel', 1, True)] - e[('sel', 0, True)]) if c.ninst > 1 else 5
    names = dict(COP_PAGE_X=STUBS >> 8, COP_PAGE_L=(STUBS >> 8) + 2, COP_VINIT=e[('vinit', True)] & 255,
                 COP_CUT=e[('cut', True)] & 255, COP_VIB=e[('vib', True)] & 255)
    for op in OPS + COMBOS:
        for xen in (True, False):                          # the same offsets in both modes' pages
            assert e[(op, 0, xen)] & 255 == e[(op, 0, True)] & 255
            assert e[(op, 0, xen)] >> 8 == names['COP_PAGE_X' if xen else 'COP_PAGE_L'] + (op in COMBOS)
        names['COP_%s0' % op.upper()] = e[(op, 0, True)] & 255
    names.update(COP_STRIDE=stride, COP_HPV=d['hpv'], COP_VOICES=64 // d['hpv'], COP_NINST=c.ninst)
    with open(out + '.h', 'w') as f:
        f.write('/* %s: generated by copgen.py from %s (the copper note engine) */\n' % (os.path.basename(out) + '.h', os.path.basename(src)))
        for k, v in names.items():
            f.write('#define %-12s 0x%02X\n' % (k, v))
        for op in OPS + COMBOS:
            m = 'COP_%s(i)' % op.upper()
            f.write('#define %-12s ((unsigned char)(COP_%s0 + COP_STRIDE * (i)))\n' % (m, op.upper()))
    with open(out + '.inc', 'w') as f:
        f.write('; %s: generated by copgen.py from %s (the copper note engine)\n' % (os.path.basename(out) + '.inc', os.path.basename(src)))
        for k, v in names.items():
            f.write('%-12s = $%02X\n' % (k, v))
    print('%s: image %d bytes at $%04X (tables %d, code %d), loader %d bytes; %d x %d harmonics, %d instruments' % (
        out, len(img), base, len(c.tables), len(c.code), len(loader_xex(img, base)), 64 // d['hpv'], d['hpv'], c.ninst))


if __name__ == '__main__':
    main()
